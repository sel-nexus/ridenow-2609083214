import { test, expect, guest, localFuture } from './helpers';

test('protected pages reject a signed-out visitor and show their own data after sign in', async ({ page }) => {
  await page.goto('/activity');
  await expect(page.getByRole('heading', { name: 'Sign in to continue' })).toBeVisible();
  await expect(page.getByText('Simulated balance:')).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Go to sign in' })).toBeVisible();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Account', exact: true }).click();
  await expect(page).toHaveURL(/\/account$/);
  await expect(page.getByRole('heading', { name: 'Sign in to continue' })).toBeVisible();
  await expect(page.getByText('Simulated balance:')).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Go to sign in' })).toBeVisible();
  await page.getByRole('link', { name: 'Go to sign in' }).click();
  const entry = page.waitForResponse(r => r.url().endsWith('/identity/enter') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Continue as guest' }).click();
  expect((await entry).status()).toBe(200);
  await page.getByRole('link', { name: 'Activity', exact: true }).click();
  await expect(page.getByText('No completed journeys yet.')).toBeVisible();
  await expect(page.getByText('No upcoming reservations.')).toBeVisible();
  await page.getByRole('link', { name: 'Account', exact: true }).click();
  await expect(page.getByText('Simulated balance: ₹0.00. No real money is added or charged.')).toBeVisible();
});

test('mobile navigation and theme persist across routes and reload', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await guest(page);
  const nav = page.getByRole('navigation', { name: 'Main navigation' });
  await nav.getByRole('link', { name: 'Account' }).click();
  await page.getByLabel('Theme').selectOption('dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.reload();
  await expect(page.getByLabel('Theme')).toHaveValue('dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await nav.getByRole('link', { name: 'Services' }).click();
  await expect(page.getByRole('heading', { name: 'Services', exact: true })).toBeVisible();
  await nav.getByRole('link', { name: 'Activity' }).click();
  await expect(page.getByText('No completed journeys yet.')).toBeVisible();
  await nav.getByRole('link', { name: 'Home' }).click();
  await page.getByRole('button', { name: 'Go to Home' }).click();
  await expect(page.getByLabel('Search Hyderabad')).toBeVisible();
  await expect(page.locator('.leaflet-tile').first()).toHaveAttribute('src', /basemaps[.]cartocdn[.]com[/]dark_all/);
  await page.screenshot({ path: test.info().outputPath('mobile-home-dark.png'), fullPage: true });
  await nav.getByRole('link', { name: 'Account' }).click();
  await page.getByLabel('Theme').selectOption('light');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.getByLabel('Theme').selectOption('system');
  await page.reload();
  await expect(page.getByLabel('Theme')).toHaveValue('system');
});

test('reservation can be edited and cancelled and stays cancelled after reload', async ({ page }) => {
  await guest(page);
  await page.getByRole('link', { name: 'Services', exact: true }).click();
  await page.getByLabel('Future date and time').fill(localFuture(2));
  const created = page.waitForResponse(r => r.url().endsWith('/activity/schedules') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Save reservation' }).click();
  const createResponse = await created;
  expect(createResponse.status()).toBe(201);
  const reservation = await createResponse.json();
  await expect(page.getByText('Reservation saved. No payment or dispatch occurred.')).toBeVisible();
  await page.getByRole('link', { name: 'Activity', exact: true }).click();
  const card = page.locator('article.activity-card').filter({ hasText: reservation.destination.name });
  await card.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Future date and time').fill(localFuture(3));
  await page.getByLabel('Vehicle').selectOption('auto');
  const updated = page.waitForResponse(r => r.url().endsWith(`/activity/schedules/${reservation.id}`) && r.request().method() === 'PUT');
  await page.getByRole('button', { name: 'Save changes' }).click();
  expect((await updated).status()).toBe(200);
  await expect(card).toContainText('Auto');
  await page.reload();
  await expect(card).toContainText('Auto');
  page.once('dialog', dialog => dialog.accept());
  const cancelled = page.waitForResponse(r => r.url().endsWith(`/activity/schedules/${reservation.id}/cancel`) && r.request().method() === 'POST');
  await card.getByRole('button', { name: 'Cancel reservation' }).click();
  expect((await cancelled).status()).toBe(200);
  await expect(page.getByText('Reservation cancelled. No fee was charged.')).toBeVisible();
  await expect(page.getByText('No upcoming reservations.')).toBeVisible();
  await page.reload();
  await expect(page.getByText('No upcoming reservations.')).toBeVisible();
});

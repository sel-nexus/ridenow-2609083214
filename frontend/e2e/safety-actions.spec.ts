import { test, expect, guest } from './helpers';

test('tracking offers simulated contact, SOS, share and RideCheck actions', async ({ page, context }) => {
  test.setTimeout(150000);
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  const session = await guest(page);
  await page.getByRole('button', { name: 'Go to Home' }).click();
  const search = page.waitForResponse(r => r.url().includes('/locations/search?q=RGIA') && r.status() === 200);
  await page.getByLabel('Search Hyderabad').fill('RGIA');
  const airport = (await (await search).json()).items[0];
  await page.getByRole('button', { name: /Rajiv Gandhi International Airport/ }).click();
  const quoted = page.waitForResponse(r => r.url().endsWith('/booking/quotes') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Compare rides' }).click();
  const quoteResponse = await quoted;
  expect(quoteResponse.status()).toBe(201);
  expect((await quoteResponse.json()).destination.name).toBe(airport.name);
  const booked = page.waitForResponse(r => r.url().endsWith('/booking/rides') && r.request().method() === 'POST');
  await page.getByRole('button', { name: /Confirm simulated booking/ }).click();
  const bookingResponse = await booked;
  expect(bookingResponse.status()).toBe(201);
  const booking = await bookingResponse.json();
  expect(booking.destination.name).toBe(airport.name);
  const tracked = page.waitForResponse(r => r.url().endsWith(`/tracking/${booking.id}`) && r.request().method() === 'GET');
  await page.getByRole('button', { name: 'Track Your Ride' }).click();
  const trackingResponse = await tracked;
  expect(trackingResponse.status()).toBe(200);
  expect((await trackingResponse.json()).booking.id).toBe(booking.id);

  await page.getByRole('button', { name: 'Mock call' }).click();
  await expect(page.getByText(/No phone call is placed/)).toBeVisible();
  await page.getByRole('button', { name: 'End mock call' }).click();
  await expect(page.getByText(/No phone call is placed/)).toHaveCount(0);
  await page.getByRole('button', { name: 'Mock chat' }).click();
  await expect(page.getByText('Mock chat · no message is sent.')).toBeVisible();
  await page.getByRole('button', { name: "I'm at the pickup point" }).click();
  await expect(page.getByRole('status').filter({ hasText: "Simulated message: I'm at the pickup point · Driver: Thanks, see you soon." })).toBeVisible();
  await page.getByRole('button', { name: 'Close chat' }).click();
  await expect(page.getByText('Mock chat · no message is sent.')).toHaveCount(0);
  await page.getByRole('button', { name: 'Safety shield' }).click();
  await expect(page.getByText('Simulated SOS 112 · no emergency service will be contacted.')).toBeVisible();
  await expect(page.getByText(/Simulated GPS:/)).toContainText(booking.pickup.lat.toFixed(5));
  await page.getByRole('button', { name: 'Simulate SOS' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'SOS simulation only: no emergency service was contacted.' })).toBeVisible();
  await page.getByRole('button', { name: 'Share Trip' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Simulated trip reference copied. It is not a live tracking link.' })).toBeVisible();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(`${new URL(page.url()).origin}/#simulated-trip-${booking.id}`);
  await page.getByRole('button', { name: 'Close safety' }).click();
  await expect(page.getByText('Safety simulation')).toHaveCount(0);

  await expect(page.getByText('Driver has arrived')).toBeVisible({ timeout: 70000 });
  const pin = await page.locator('.tracking-pin').textContent();
  expect(pin).toMatch(/^\d{4}$/);
  await page.getByLabel(/Enter safety PIN/).fill(pin!);
  const started = page.waitForResponse(r => r.url().endsWith(`/tracking/${booking.id}/pin`) && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Start Trip' }).click();
  const startResponse = await started;
  expect(startResponse.status()).toBe(200);
  expect((await startResponse.json()).state).toBe('in_trip');
  await expect(page.getByText('Trip in progress')).toBeVisible();
  await expect(page.getByText('Everything okay on your trip? (Simulated RideCheck)')).toBeVisible({ timeout: 20000 });
  await page.getByRole('button', { name: 'Yes, I’m okay' }).click();
  await expect(page.getByText('RideCheck acknowledged.')).toBeVisible();
  await expect(page.getByText('Everything okay on your trip? (Simulated RideCheck)')).toHaveCount(0);
  const persisted = await page.request.get(`/api/v1/tracking/${booking.id}`, { headers: { Authorization: `Bearer ${session.token}` } });
  expect(persisted.status()).toBe(200);
  expect((await persisted.json()).booking.id).toBe(booking.id);
});
